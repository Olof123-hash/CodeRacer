  /** Opens the settings window, or brings it back to the front when it is already open. */
  private void gameSettings() {
    if (settingsWindow == null || !settingsWindow.isDisplayable()) {
      // The window edits the settings object of this screen, so it reads the new values from the
      // same object instead of copying them.
      settingsWindow = new SettingsPanel(settings);
      settingsWindow.addSettingsChangeListener(this::settingsChanged);
      // The settings are shown next to the race window in the same way as the other popups, so the
      // buttons of the race screen stay usable.
      WindowStyler.placePopup(
          this, settingsWindow, WindowStyler.Corner.TOP_RIGHT, historyWindow, overWindow);
      settingsWindow.setVisible(true);
    } else {
      settingsWindow.toFront();
    }
  }

  /**
   * Runs when the player changes something in the settings window. The window has already written
   * the new values into the settings object, so this method only has to apply them.
   */
  private void settingsChanged() {
    // The palette. Every styler stores the colours it uses in the components it styles, so the
    // scheme is applied again and this screen is styled again to show the new colours.
    Theme.applyScheme(
        ColourScheme.byName(settings.getScheme()), new Color(settings.getCustomAccent()));
    // The three typing colours are settings of their own; applyTheme re-applies the caret and
    // colorTypingField() repaints the text that is already on the screen.
    Theme.applyTypingColours(
        new Color(settings.getCaretColour()),
        new Color(settings.getCorrectColour()),
        new Color(settings.getErrorColour()),
        new Color(settings.getTextColour()));
    applyTheme();

    // The background behind the race screen
    showBackground(settings.getBackground());

    // The content type. The drop down lists languages or text sources, depending on the switch.
    applyContentMode();

    // The settings window paints itself with the theme as well, so it is styled again too.
    if (settingsWindow != null) {
      settingsWindow.refreshTheme();
    }

    // The popups are built from the palette when they are created, so they are closed here and
    // open again in the new colours the next time they are needed.
    if (overWindow != null) {
      overWindow.dispose();
    }
    if (historyWindow != null) {
      historyWindow.dispose();
    }

    // The snippet still has the colours of the previous scheme or typing colours, so it is
    // coloured again. It is done in every state, so a finished race keeps up as well.
    if (currentRace != null) {
      colorTypingField();
      SwingUtilities.invokeLater(this::applySnippetFont);
    }
    revalidate();
    repaint();
  }

  /**
   * Fills the "Select Language" drop down with the options that belong to the current content type
   * (code snippets or plain text) and selects the value that is stored in the settings.
   */
  private void applyContentMode() {
    String[] options = settings.isCodeMode() ? CODE_OPTIONS : TEXT_OPTIONS;
    String preferred = settings.isCodeMode() ? settings.getLanguage() : settings.getTextSource();

    // Setting the model fires action events for the selection that comes with it. The handler of
    // the drop down would read that as the player picking another language.
    repopulatingLanguages = true;
    try {
      jComboBox1.setModel(new DefaultComboBoxModel<>(options));
      jComboBox1.setSelectedItem(contains(options, preferred) ? preferred : options[0]);
    } finally {
      repopulatingLanguages = false;
    }

    // The caption above the drop down follows the content type
    jLabel2.setText(settings.isCodeMode() ? "Select Language" : "Select Text");
    revalidate();
    repaint();
  }

  /** Tells whether the options of a drop down contain a value. */
  private boolean contains(String[] options, String value) {
    for (String option : options) {
      if (option.equals(value)) {
        return true;
      }
    }
    return false;
  }

